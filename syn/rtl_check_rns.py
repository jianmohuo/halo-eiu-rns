import sys, os, json, random
from math import gcd

W_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RTL_DIR = os.path.join(W_ROOT, "rtl")
TB_DIR = os.path.join(W_ROOT, "tmp", "tb")
for d in (RTL_DIR, TB_DIR):
    os.makedirs(d, exist_ok=True)

# ---------------------------------------------------------------- moduli search
def search_moduli(total_bits, verbose=False, bmax=None):
    """贪心互质搜索: 1x 2^32 (截断免费) + {2^b - c} 伪梅森族 (c<=39).
    1024b: b<=36 (32b 级通道 k~35); 4096b: 允许 64b 级 (k~91)."""
    if bmax is None:
        bmax = 36 if total_bits <= 1024 else 66
    sel = [(32, 0, 1 << 32)]
    bits = 32.0
    cand = []
    for c in range(1, 40, 2):
        for b in range(bmax, 21, -1):
            m = (1 << b) - c
            if m & 1 and m > 1:
                cand.append((b, c, m))
    cand.sort(key=lambda t: (t[1], -t[0]))          # c 小优先, b 大优先
    for (b, c, m) in cand:
        if bits >= total_bits + 8:
            break
        if all(gcd(m, mm) == 1 for (_, _, mm) in sel):
            sel.append((b, c, m))
            bits += m.bit_length()
    P = 1
    for (_, _, m) in sel:
        P *= m
    assert P >= (1 << total_bits), f"range short: {P.bit_length()}"
    if verbose:
        print(f"k={len(sel)} channels, P = 2^{P.bit_length()-1}..., "
              f"range {P.bit_length()} bits")
    return sel

# ---------------------------------------------------------------- RNS reference
def inv_mod(a, m):
    g, x, _ = _egcd(a % m, m)
    assert g == 1, "moduli not coprime"
    return x % m

def _egcd(a, b):
    if b == 0:
        return (a, 1, 0)
    g, x, y = _egcd(b, a % b)
    return (g, y, x - (a // b) * y)

def fwd(x, sel):
    return [x % m for (_, _, m) in sel]

class RNSRef:
    def __init__(self, sel):
        self.sel = sel
        self.P = 1
        for (_, _, m) in sel:
            self.P *= m

    def mac_step(self, acc_res, a, b):
        return [(ai + (a % m) * (b % m)) % m
                for ai, (_, _, m) in zip(acc_res, self.sel)]

    def mrc_hw_model(self, res):
        """RTL rns_mrc_converter 逐拍行为模型 (S-RNS 递推 + Horner)."""
        k = len(self.sel)
        m = [t[2] for t in self.sel]
        Mprev = [1] * (k + 1)
        for j in range(1, k + 1):
            Mprev[j] = Mprev[j - 1] * m[j - 1]
        inv = [inv_mod(Mprev[j] % m[j], m[j]) for j in range(k)]  # 0-based
        S = [0] * k      # S_rns[i] (渐进)
        gp = [1] * k     # M_row mod m_i
        d = [0] * k
        for j in range(1, k + 1):
            u = (res[j - 1] - S[j - 1]) % m[j - 1]
            d[j - 1] = u * inv[j - 1] % m[j - 1]
            for i in range(j + 1, k + 1):
                S[i - 1] = (S[i - 1] + d[j - 1] * gp[i - 1]) % m[i - 1]
            for i in range(j + 1, k + 1):
                gp[i - 1] = gp[i - 1] * (m[j - 1] % m[i - 1]) % m[i - 1]
        T = 0
        for j in range(k, 0, -1):
            T = T * m[j - 1] + d[j - 1]
        return T

    def value_of(self, res):
        X = 0
        for r, (_, _, m) in zip(res, self.sel):
            Mi = self.P // m
            X += r * Mi * inv_mod(Mi % m, m)
        return X % self.P

# ---------------------------------------------------------------- vh params
def gen_vh(total_bits):
    sel = search_moduli(total_bits, verbose=True)
    k = len(sel)
    m = [t[2] for t in sel]
    Mprev = [1] * (k + 1)
    for j in range(1, k + 1):
        Mprev[j] = Mprev[j - 1] * m[j - 1]
    inv = [inv_mod(Mprev[j] % m[j], m[j]) for j in range(k)]
    gam = [[m[a] % m[b] for b in range(k)] for a in range(k)]
    WMAX = max(t[0] for t in sel)
    lines = []
    lines.append(f"// AUTO-GENERATED by syn/rtl_check_rns.py -- RNS moduli table, TOTAL_BITS={total_bits}")
    lines.append(f"// k = {k} channels, P = {Mprev[k].bit_length()} bit dynamic range (>= 2^{total_bits})")
    lines.append(f"// Per Halo Paper App. F/G; moduli per LITERATURE_MAPPING.md sec.2")
    lines = lines[:5]
    lines.append("parameter integer NK = %d;" % k)
    lines.append("parameter integer BMAX = %d;" % WMAX)

    def emit(name, vals, width, prefix):
        out = ["function %s%s; input integer idx; begin" % (width, name)]
        out.append("  case (idx)")
        for i, v in enumerate(vals):
            out.append("    %d: %s = %s%d;" % (i, name, prefix, v))
        out.append("    default: %s = %s0;" % (name, prefix))
        out.append("  endcase end")
        out.append("endfunction")
        return "\n".join(out)

    lines.append(emit("ch_b",   [t[0] for t in sel], "[6:0] ", "'d"))
    lines.append(emit("ch_c",   [t[1] for t in sel], "[5:0] ", "'d"))
    lines.append(emit("ch_m",   [t[2] for t in sel], "[%d:0] " % WMAX, "'d"))
    lines.append(emit("ch_inv", inv,                 "[%d:0] " % WMAX, "'d"))
    gam_flat = [gam[a][b] for a in range(k) for b in range(k)]
    lines.append(emit("ch_gam", gam_flat,            "[%d:0] " % WMAX, "'d"))
    vh = os.path.join(RTL_DIR, f"eiu_rns_moduli_{total_bits}.vh")
    open(vh, "w").write("\n".join(lines) + "\n")
    meta = {"total_bits": total_bits, "k": k,
            "channels": [{"b": b, "c": c, "m": mm} for (b, c, mm) in sel],
            "P_bits": Mprev[k].bit_length(), "gam": gam}
    json.dump(meta, open(os.path.join(RTL_DIR, f"eiu_rns_moduli_{total_bits}.json"), "w"), indent=1)
    print(f"wrote {vh} (k={k})")
    return sel

# ---------------------------------------------------------------- vectors
def gen_vectors(total_bits, steps=8, nvecs=6, seed=20261027):
    sel = search_moduli(total_bits)
    ref = RNSRef(sel)
    rng = random.Random(seed)
    k = len(sel)
    BMAX = max(t[0] for t in sel)
    vec_lines, exp_recs = [], []
    for v in range(nvecs):
        acc = [0] * k
        X = 0
        for s in range(steps):
            a = rng.getrandbits(32)
            b = rng.getrandbits(32)
            vec_lines += [f"{a % m:x}" for (_, _, m) in sel]
            vec_lines += [f"{b % m:x}" for (_, _, m) in sel]
            acc = ref.mac_step(acc, a, b)
            X = (X + a * b) % ref.P
        exp_recs.append({"vec": v, "acc": [f"{x:x}" for x in acc],
                         "X": f"{X:x}", "P_bits": ref.P.bit_length()})
    vecf = os.path.join(TB_DIR, f"rns_vec_{total_bits}.txt")
    expf = os.path.join(TB_DIR, f"rns_expect_{total_bits}.json")
    open(vecf, "w").write("\n".join(vec_lines) + "\n")
    json.dump(exp_recs, open(expf, "w"), indent=1)
    print(f"vectors: {nvecs} x {steps} MAC steps -> {vecf}")
    print(f"expects -> {expf}")

# ---------------------------------------------------------------- check
def check(total_bits, path):
    expects = json.load(open(os.path.join(TB_DIR, f"rns_expect_{total_bits}.json")))
    acc_got, mrc_got = {}, {}
    for line in open(path):
        t = line.split()
        if len(t) >= 4 and t[0] == "ACC":
            acc_got[(int(t[1]), int(t[2]))] = t[3]
        elif len(t) >= 3 and t[0] == "X":
            mrc_got[int(t[1])] = t[2]
    nerr = ntot = 0
    for rec in expects:
        v = rec["vec"]
        for i, want in enumerate(rec["acc"]):
            ntot += 1
            got = acc_got.get((v, i))
            if got is None or int(got, 16) != int(want, 16):
                nerr += 1
                if nerr <= 4:
                    print(f"  ACC MISMATCH vec={v} ch={i}: got={got} want={want}")
        ntot += 1
        gotx = mrc_got.get(v)
        if gotx is None or int(gotx, 16) != int(rec["X"], 16):
            nerr += 1
            if nerr <= 4:
                print(f"  MRC MISMATCH vec={v}: got={(gotx or 'None')[:20]} "
                      f"want={rec['X'][:20]}...")
    status = "PASS" if nerr == 0 else "FAIL"
    print(f"check{total_bits}: {ntot} checks, {nerr} errors -> {status}")
    return nerr == 0

# ---------------------------------------------------------------- selftest
def selftest(total_bits):
    sel = search_moduli(total_bits, verbose=True)
    ref = RNSRef(sel)
    rng = random.Random(7)
    ok = True
    for _ in range(5):
        X = rng.randrange(ref.P)
        res = fwd(X, sel)
        mrcX = ref.mrc_hw_model(res)
        dirX = ref.value_of(res)
        hwX = ref.mrc_hw_model(res)
        if not (mrcX == X and dirX == X and hwX == X):
            ok = False
            print("  SELFTEST FAIL", hex(X)[:18])
    for X in (ref.P - 1, ref.P // 2, (1 << total_bits) - 1):
        res = fwd(X, sel)
        if not (ref.mrc_hw_model(res) == X and ref.value_of(res) == X):
            ok = False
            print("  SELFTEST BOUNDARY FAIL", hex(X)[:18])
    for _ in range(3):
        acc = [0] * len(sel)
        X = 0
        for _s in range(10):
            a, b = rng.getrandbits(32), rng.getrandbits(32)
            acc = ref.mac_step(acc, a, b)
            X = (X + a * b) % ref.P
        if [x % m for x, (_, _, m) in zip(acc, sel)] != fwd(X, sel):
            ok = False
            print("  SELFTEST MAC FAIL")
    print("selftest:", "PASS" if ok else "FAIL")
    return ok

if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "selftest"
    tb = int(sys.argv[2]) if len(sys.argv) > 2 and sys.argv[2].isdigit() else 1024
    if cmd == "selftest":
        sys.exit(0 if selftest(tb) else 1)
    elif cmd == "params":
        gen_vh(tb)
    elif cmd == "gen":
        steps = int(sys.argv[3]) if len(sys.argv) > 3 else 8
        nvecs = int(sys.argv[4]) if len(sys.argv) > 4 else 6
        gen_vectors(tb, steps, nvecs)
    elif cmd == "check":
        sys.exit(0 if check(tb, sys.argv[3]) else 1)
    else:
        print(__doc__)
